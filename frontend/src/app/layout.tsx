import type { Metadata } from "next";
import { connection } from "next/server";
import { headers } from "next/headers";
import localFont from "next/font/local";
import { Toaster } from "sonner";
import { STAGE_UI } from "@/lib/stage-flag";
import { Analytics } from "@/components/analytics";
import "./globals.css";

const geistSans = localFont({ src: "./fonts/geist.ttf", variable: "--font-geist-sans", weight: "100 900", display: "swap" });
const geistMono = localFont({ src: "./fonts/geistmono.ttf", variable: "--font-geist-mono", weight: "100 900", display: "swap" });
const archivo = localFont({ src: "./fonts/archivo.ttf", variable: "--font-archivo", weight: "100 900", display: "swap" });

export const metadata: Metadata = {
  metadataBase: new URL(
    process.env.NEXT_PUBLIC_SITE_URL || "https://scalecad.ai"
  ),
  title: "ScaleCAD — Can you make it?",
  description:
    "Check manufacturing options, review design findings, and trace the resources behind your next decision. Explore a recorded sample without an account.",
  alternates: { canonical: "/" },
  icons: {
    icon: "/icon.svg",
  },
  openGraph: {
    title: "ScaleCAD — Can you make it?",
    description:
      "Makeability verification for real manufacturing decisions.",
    url: "/",
    siteName: "ScaleCad",
    images: [{ url: "/opengraph-image", width: 1200, height: 630 }],
    type: "website",
  },
  twitter: {
    card: "summary_large_image",
    title: "ScaleCAD — Can you make it?",
    description:
      "Makeability verification for real manufacturing decisions.",
    images: ["/opengraph-image"],
  },
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // A fresh CSP nonce is generated by proxy.ts for every document request.
  // Nonces require dynamic rendering; this is an explicit security tradeoff
  // for a product that handles customer CAD and authentication material.
  await connection();
  const nonce = (await headers()).get("x-nonce") || undefined;
  return (
    <html
      lang="en"
      // Stage-UI gate: when NEXT_PUBLIC_STAGE_UI is on, `[data-stage]` swaps the
      // semantic tokens onto the D5 stage register (see globals.css). Off = the
      // attribute is omitted entirely → today's graphite UI, byte-identical.
      data-stage={STAGE_UI ? "" : undefined}
      className={`${geistSans.variable} ${geistMono.variable} ${archivo.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        {/* No-flash theme: ScaleCad is light-first. Dark remains an explicit
            user preference, but route changes never imply a theme change. */}
        <script
          nonce={nonce}
          // Browsers deliberately hide a parsed script nonce from DOM attribute
          // reads. React therefore sees an empty client-side attribute even
          // though the server supplied the correct nonce; suppress only that
          // security-defined mismatch on this exact element.
          suppressHydrationWarning
          dangerouslySetInnerHTML={{
            __html:
              "try{if(localStorage.getItem('cv_theme')==='dark'){document.documentElement.classList.add('dark')}}catch(e){}",
          }}
        />
      </head>
      <body className="min-h-full flex flex-col">
        {children}
        <Analytics token={process.env.POSTHOG_PROJECT_TOKEN || ""} nonce={nonce} />
        {/* Toasts live bottom-right so they never occlude the top-right control
            cluster (⌘K / Jump / notifications bell) or their dropdowns — a
            recurring finding (W4 + W7). One place, fixed everywhere. */}
        <Toaster position="bottom-right" richColors closeButton />
      </body>
    </html>
  );
}
